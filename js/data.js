async function fetchJsonWithFallback(relativePath, fallbackData) {
  try {
    const response = await fetch(relativePath, {
      headers: { 'Accept': 'application/json' }
    });
    if (!response.ok) {
      throw new Error(`HTTP ${response.status} al cargar ${relativePath}`);
    }
    return await response.json();
  } catch (err) {
    console.warn(`[JAZIEL.DEV] Usando respaldo integrado para ${relativePath}:`, err.message);
    return fallbackData;
  }
}

export async function loadAllPortfolioData() {
  const [projects, profile, skills] = await Promise.all([
    fetchJsonWithFallback('./data/projects.json', FALLBACK_PROJECTS),
    fetchJsonWithFallback('./data/profile.json', FALLBACK_PROFILE),
    fetchJsonWithFallback('./data/skills.json', FALLBACK_SKILLS)
  ]);

  const publishedProjects = Array.isArray(projects)
    ? projects
        .filter((p) => p && p.published === true)
        .sort((a, b) => (a.sortOrder ?? 999) - (b.sortOrder ?? 999))
    : [];

  return {
    allProjects: projects || [],
    publishedProjects,
    profile: profile || FALLBACK_PROFILE,
    skills: skills || FALLBACK_SKILLS
  };
}

export async function getPublishedProjectBySlug(slug) {
  const { publishedProjects } = await loadAllPortfolioData();
  if (!slug) return publishedProjects[0] || null;
  return publishedProjects.find((p) => p.slug === slug || p.id === slug) || null;
}
